# ---------- DOCX helpers ----------
def set_cell_shading(cell, fill):
    tcPr=cell._tc.get_or_add_tcPr(); shd=OxmlElement('w:shd'); shd.set(qn('w:fill'),fill); tcPr.append(shd)

def set_cell_text(cell,text,bold=False,size=9):
    cell.text=''; p=cell.paragraphs[0]; r=p.add_run(str(text)); r.bold=bold; r.font.name='DejaVu Sans'; r._element.rPr.rFonts.set(qn('w:eastAsia'),'DejaVu Sans'); r.font.size=Pt(size)

def setup_doc(title, subtitle=None):
    doc=Document(); sec=doc.sections[0]; sec.top_margin=Cm(1.5); sec.bottom_margin=Cm(1.5); sec.left_margin=Cm(1.7); sec.right_margin=Cm(1.7)
    for sname,sz in [('Normal',10),('Heading 1',16),('Heading 2',13),('Heading 3',11)]:
        st=doc.styles[sname]; st.font.name='DejaVu Sans'; st._element.rPr.rFonts.set(qn('w:eastAsia'),'DejaVu Sans'); st.font.size=Pt(sz)
    h=doc.add_heading(title,1); h.alignment=WD_ALIGN_PARAGRAPH.CENTER
    if subtitle:
        p=doc.add_paragraph(subtitle); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p=doc.add_paragraph('ФОС дисциплины «Компьютерное зрение». Модуль 2. Редакция 3.0.'); p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    return doc

def add_table(doc,headers,rows,widths=None):
    t=doc.add_table(rows=1,cols=len(headers)); t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for i,h in enumerate(headers): set_cell_text(t.rows[0].cells[i],h,True); set_cell_shading(t.rows[0].cells[i],'D9EAF7')
    for row in rows:
        cells=t.add_row().cells
        for i,val in enumerate(row): set_cell_text(cells[i],val); cells[i].vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.TOP
    doc.add_paragraph(''); return t

def add_bullets(doc,items):
    for x in items: doc.add_paragraph(x,style='List Bullet')

def add_numbers(doc,items):
    for x in items: doc.add_paragraph(x,style='List Number')

def add_code(doc,text):
    p=doc.add_paragraph(); p.paragraph_format.left_indent=Cm(0.7); p.paragraph_format.right_indent=Cm(0.7)
    r=p.add_run(text); r.font.name='DejaVu Sans Mono'; r._element.rPr.rFonts.set(qn('w:eastAsia'),'DejaVu Sans Mono'); r.font.size=Pt(9)
    shd=OxmlElement('w:shd'); shd.set(qn('w:fill'),'F3F4F6'); p._p.get_or_add_pPr().append(shd)

