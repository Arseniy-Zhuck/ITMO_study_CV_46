# repository tree and manifest
def tree(path,prefix=''):
    entries=sorted(path.iterdir(),key=lambda p:(p.is_file(),p.name.lower()))
    lines=[]
    for i,p in enumerate(entries):
        last=i==len(entries)-1; lines.append(prefix+('└── ' if last else '├── ')+p.name)
        if p.is_dir(): lines+=tree(p,prefix+('    ' if last else '│   '))
    return lines
(ROOT/'docs/repository-tree.txt').write_text('.\n'+'\n'.join(tree(ROOT)),encoding='utf-8')

